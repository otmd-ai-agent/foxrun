"""Small local-model tool loop over real Foxrun commands. No arbitrary shell tool."""
import json
import os
import re
import sqlite3
import subprocess
import sys
import time
import urllib.request
from settings import *


def work(*args):
    env = dict(os.environ, FOXRUN_HOME=str(SYSTEM), FOXRUN_PORTFOLIO=str(PORTFOLIO))
    result = subprocess.run([sys.executable, str(SYSTEM / 'work/work.py'), '--workspace', 'demo', '--receipt-root', str(WORKSPACE), *args], env=env, capture_output=True, text=True, timeout=30)
    return {'ok': result.returncode == 0, 'output': (result.stdout + result.stderr).strip()[-6000:]}


def tasks():
    db = WORKSPACE / 'data.db'
    if not db.exists(): db = SYSTEM / 'data.db'
    if not db.exists(): return []
    with sqlite3.connect(db.as_uri() + '?mode=ro', uri=True) as connection:
        connection.row_factory = sqlite3.Row
        rows = [dict(r) for r in connection.execute('SELECT id,title,status,acceptance,owner,claimed_by FROM tasks ORDER BY created_on,id')]
    for row in rows:
        if row.get('acceptance'):
            try:
                checks=json.loads(row['acceptance'])
                if isinstance(checks,list): row['acceptance']='; '.join(str(c) for c in checks)
            except (ValueError,TypeError): pass
        proof = WORKSPACE / 'notes' / ('proof-' + row['id'] + '.md')
        row['proof'] = proof.read_text() if proof.is_file() else None
    return rows


def task_id(value):
    if not isinstance(value, str) or not re.fullmatch(r'T[0-9]+', value): raise ValueError('Expected a task ID such as T2.')
    if value not in {t['id'] for t in tasks()}: raise ValueError('Task does not exist.')
    return value


def field(args, key, limit=3000):
    value = args.get(key)
    if not isinstance(value, str) or not value.strip() or len(value) > limit: raise ValueError(f'{key} must be nonempty text, at most {limit} characters.')
    return value.strip()


def execute(name, args):
    if not isinstance(args, dict): raise ValueError('Tool arguments must be an object.')
    if name == 'list_tasks': return {'tasks': tasks()}
    if name == 'create_task':
        return work('create', '--by', 'demo-lead', '--title', field(args, 'title', 160), '--problem', field(args, 'problem'), '--body', field(args, 'body'), '--acceptance', field(args, 'acceptance'), '--job-when', 'When exploring this disposable Foxrun demo', '--job-want', 'I want to complete a small demonstration task', '--job-so', 'So I can inspect proof and independently review it', '--context', 'Synthetic demonstration work only. No external actions or business accounts.', '--where', 'STATE.md')
    if name == 'submit_proof':
        ident = task_id(args.get('task_id')); content = field(args, 'content', 5000)
        row = next(t for t in tasks() if t['id'] == ident)
        if row['status'] not in ('todo', 'in-progress'): raise ValueError('Only todo or in-progress demo tasks can receive proof.')
        dest = WORKSPACE / 'notes' / f'proof-{ident}.md'
        if dest.exists(): raise ValueError('Proof already exists; this demo does not overwrite submitted proof.')
        claimed = work('claim', ident, '--by', 'demo-lead')
        if not claimed['ok']: return claimed
        dest.parent.mkdir(exist_ok=True)
        dest.write_text(f'# Demo proof for {ident}\n\nGenerated by the local demo model. Review before accepting.\n\n{content}\n')
        result = work('done', ident, '--proof', str(dest.relative_to(WORKSPACE)), '--note', 'Local model submitted demo proof for the visitor to review.', '--by', 'demo-lead')
        if not result['ok']: dest.unlink()  # only the new file from this failed submission
        return result
    raise ValueError('Unknown tool. The demo does not offer shell, network, or acceptance tools.')


def schema(name, description, properties):
    return {'type': 'function', 'function': {'name': name, 'description': description, 'parameters': {'type': 'object', 'properties': {k: {'type': 'string', 'description': v} for k,v in properties.items()}, 'required': list(properties), 'additionalProperties': False}}}

TOOLS = [
    schema('list_tasks', 'Read the real Foxrun demo task records and saved proof. Use this to recover work after a new chat.', {}),
    schema('create_task', 'Create a real Foxrun task. Call only when the visitor requests a new task; do not duplicate one.', {'title':'Short title', 'problem':'Problem to solve', 'body':'Work to do', 'acceptance':'Concrete check that proves completion'}),
    schema('submit_proof', 'Save a Markdown deliverable for an existing task and submit it for human review. This does NOT accept the task.', {'task_id':'Existing task ID, e.g. T2', 'content':'The actual deliverable, such as the requested checklist. Do not claim real-world actions occurred.'})
]
SYSTEM_PROMPT = '''You are the small local model in a disposable Foxrun demo. Use the tools to read and change REAL demo records. Be concise. Never say you created or completed a task unless a successful tool result proves it. Do not invent task IDs. When asked to resume or show work, call list_tasks. To create work, call create_task. Before writing a deliverable, call list_tasks to read its title and acceptance. Then write useful, concrete content and call submit_proof. Never submit placeholders like Item 1, Item 2, or TODO. A checklist for trying Foxrun should explain real demo steps: create a task, read its saved proof, and accept it after review. Only the visitor can accept work, using the separate Review and accept button after reading the proof. You cannot accept your own work, send messages, browse, run shell commands, or change external systems. Everything here is synthetic demo work. If asked for those actions, explain the limit. Tools may fail; report the error honestly. Ask one short clarification if essential information is missing. Avoid long plans and reasoning. After a successful tool result, answer briefly and stop.'''


def chat(user_text, history, on_event=lambda event: None):
    if not isinstance(user_text, str) or not user_text.strip() or len(user_text) > 2000: raise ValueError('Enter 1–2000 characters.')
    # Bound prompt size on a 4096-token CPU model. A fresh chat can recover records with list_tasks.
    recent=[]; budget=4000
    for old in reversed(history[-6:]):
        size=len(old.get('content',''))
        if size>budget: break
        recent.insert(0,old); budget-=size
    messages = [{'role':'system','content':SYSTEM_PROMPT}, *recent, {'role':'user','content':user_text}]
    started=time.monotonic(); events=[]; tokens=0
    for turn in range(4):
        payload={'model':MODEL,'messages':messages,'tools':TOOLS,'temperature':0.1,'max_tokens':600,'stream':False,'chat_template_kwargs':{'enable_thinking':False}}
        request=urllib.request.Request(MODEL_HOST+'/engines/llama.cpp/v1/chat/completions', data=json.dumps(payload).encode(), headers={'Content-Type':'application/json'})
        with urllib.request.urlopen(request, timeout=240) as response: result=json.load(response)
        tokens += result.get('usage',{}).get('completion_tokens',0)
        message=result['choices'][0]['message']; calls=message.get('tool_calls') or []
        if not calls:
            answer=message.get('content')
            source='model'
            if not answer:
                source='foxrun'
                lines=[]
                for event in events:
                    r=event['result']
                    if event['tool']=='list_tasks': lines.append(f"Found {len(r.get('tasks',[]))} task records. See the task panel.")
                    else: lines.append(event['tool'] + ': ' + (r.get('output') or r.get('error') or json.dumps(r)))
                answer='\n'.join(lines) or 'The model returned no answer. Try a shorter request.'
            history.extend([{'role':'user','content':user_text},{'role':'assistant','content':answer}])
            return {'answer':answer,'answer_source':source,'events':events,'seconds':round(time.monotonic()-started,2),'completion_tokens':tokens}
        messages.append({'role':'assistant','content':message.get('content') or '', 'tool_calls':calls})
        for call in calls:
            name=call['function']['name']
            try: outcome=execute(name,json.loads(call['function']['arguments']))
            except (ValueError, OSError, subprocess.SubprocessError) as e: outcome={'ok':False,'error':str(e)}
            event={'tool':name,'result':outcome};events.append(event);on_event(event)
            messages.append({'role':'tool','tool_call_id':call['id'],'content':json.dumps(outcome)})
    return {'answer':'Stopped after four model turns. Inspect the tool results and task list before trying again.','events':events,'seconds':round(time.monotonic()-started,2),'completion_tokens':tokens}
